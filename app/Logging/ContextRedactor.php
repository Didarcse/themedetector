<?php

declare(strict_types=1);

namespace App\Logging;

use App\Core\Request;

/**
 * Allowlist-based sanitizer for structured log context.
 *
 * Only explicitly approved keys survive redaction. Sensitive values are
 * never logged: API keys, authorization headers, cookies, tokens, session
 * identifiers, bodies, headers, query strings, and free-form request values
 * are rejected or normalized to an approved value. Target URLs are reduced
 * to a host and a SHA-256 hash of the scheme, host, and port only, and client
 * addresses are reduced to an optional HMAC-SHA256 identifier.
 */
final class ContextRedactor
{
    private const MAX_LIST_ITEMS = 20;

    private const MAX_HOST_BYTES = 253;

    private const MAX_IDENTIFIER_BYTES = 64;

    private const MAX_MEDIA_TYPE_BYTES = 128;

    private const MAX_PATH_BYTES = 128;

    private const MAX_CLASS_BYTES = 255;

    private const MAX_FILE_BYTES = 255;

    /**
     * Context keys that callers may supply.
     *
     * @var list<string>
     */
    private const ALLOWED_KEYS = [
        'request_id',
        'method',
        'path',
        'status',
        'reason',
        'content_type',
        'body_bytes',
        'max_bytes',
        'declared_bytes',
        'error_codes',
        'tier',
        'limit',
        'remaining',
        'retry_after',
        'max_concurrent',
        'engine',
        'exception_class',
        'exception_file',
        'exception_line',
        'has_authorization',
        'session_present',
    ];

    /**
     * Context keys that are generated by the redactor and never accepted
     * from callers.
     *
     * @var list<string>
     */
    private const DERIVED_KEYS = ['client', 'target_host', 'target_hash'];

    /**
     * Context keys that are consumed into safe fields rather than emitted.
     *
     * @var list<string>
     */
    private const INTERNAL_KEYS = ['client_ip', 'target_url'];

    /**
     * Approved reason identifiers.
     *
     * @var list<string>
     */
    private const SAFE_REASONS = [
        'missing_or_invalid_token',
        'headers_already_sent',
        'session_start_failed',
        'session_regenerate_failed',
        'session_persist_failed',
        'storage_not_writable',
        'storage_create_failed',
        'missing_api_key',
        'invalid_authorization_scheme',
        'invalid_api_key',
        'unsupported_media_type',
        'payload_too_large',
        'invalid_json',
        'invalid_url',
        'workload_limit_reached',
        'transport_failure',
        'host_not_allowed',
        'engine_failure',
    ];

    /**
     * Approved detection engine identifiers.
     *
     * @var list<string>
     */
    private const SAFE_ENGINES = ['technology'];

    /**
     * Approved rate-limit tier identifiers.
     *
     * @var list<string>
     */
    private const SAFE_TIERS = ['anonymous', 'keyed', 'web'];

    /**
     * Approved API validation error codes.
     *
     * @var list<string>
     */
    private const SAFE_ERROR_CODES = ['url_invalid_format', 'url_invalid_type'];

    /**
     * Approved HTTP methods.
     *
     * @var list<string>
     */
    private const SAFE_METHODS = [
        'GET',
        'POST',
        'PUT',
        'PATCH',
        'DELETE',
        'HEAD',
        'OPTIONS',
        'TRACE',
        'CONNECT',
    ];

    /**
     * Application paths that may be logged. Unknown paths are omitted so a
     * caller cannot place a token or identifier in the request path and have
     * it written to the log.
     *
     * @var list<string>
     */
    private const SAFE_PATHS = [
        '/',
        '/loading',
        '/detect',
        '/health',
        '/about',
        '/robots.txt',
        '/sitemap.xml',
        '/api/v1/detect',
    ];

    /**
     * Approved media types. Unknown or suspicious values are reduced to
     * "other"; parameters such as charset and boundary are never logged.
     *
     * @var list<string>
     */
    private const SAFE_MEDIA_TYPES = [
        'application/json',
        'application/javascript',
        'application/octet-stream',
        'application/x-www-form-urlencoded',
        'application/xml',
        'image/jpeg',
        'image/png',
        'image/svg+xml',
        'multipart/form-data',
        'text/css',
        'text/html',
        'text/plain',
        'text/xml',
    ];

    public function __construct(
        private readonly ?string $hashKey = null,
    ) {
    }

    /**
     * Build safe request metadata for the current request.
     *
     * @param Request|null $request The current request, when available.
     *
     * @return array<string, mixed> The redacted request metadata.
     */
    public function requestMetadata(?Request $request): array
    {
        if ($request === null) {
            return [];
        }

        $metadata = [
            'request_id' => $request->requestId(),
            'method' => $request->method(),
            'path' => $request->uri(),
        ];

        $ip = $request->server()['REMOTE_ADDR'] ?? null;

        if (is_string($ip) && $ip !== '') {
            $metadata['client_ip'] = $ip;
        }

        return $this->redact($metadata);
    }

    /**
     * Redact an arbitrary event context.
     *
     * Unknown and secret keys are dropped. Caller-supplied target and client
     * fields are ignored, and a target_url always produces the authoritative
     * target_host and target_hash after all caller context has been processed.
     *
     * @param array<string, mixed> $context The raw event context.
     *
     * @return array<string, mixed> The redacted context.
     */
    public function redact(array $context): array
    {
        $redacted = [];
        $target = [];

        foreach ($context as $key => $value) {
            if ($key === 'target_url') {
                if (is_string($value)) {
                    $target = $this->targetMetadata($value);
                }

                continue;
            }

            if (in_array($key, self::DERIVED_KEYS, true)) {
                continue;
            }

            if (
                !in_array($key, self::ALLOWED_KEYS, true)
                && !in_array($key, self::INTERNAL_KEYS, true)
            ) {
                continue;
            }

            if ($key === 'client_ip') {
                $client = $this->clientHash($value);

                if ($client !== null) {
                    $redacted['client'] = $client;
                }

                continue;
            }

            $sanitized = $this->sanitizeValue($key, $value);

            if ($sanitized !== null) {
                $redacted[$key] = $sanitized;
            }
        }

        return $target === [] ? $redacted : array_replace($redacted, $target);
    }

    /**
     * Reduce a target URL to a host and SHA-256 hash.
     *
     * The hash covers only the normalized scheme, host, and port. Paths,
     * query strings, fragments, and credentials are excluded so guessable
     * path identifiers cannot be correlated offline.
     *
     * @param string $url The target URL.
     *
     * @return array{target_host?: string, target_hash?: string} The safe target fields.
     */
    public function targetMetadata(string $url): array
    {
        $url = trim($url);

        if ($url === '') {
            return [];
        }

        if (preg_match('#^https?://#i', $url) !== 1) {
            $url = 'https://' . $url;
        }

        $parts = parse_url($url);

        if (!is_array($parts)) {
            return [];
        }

        $scheme = strtolower((string) ($parts['scheme'] ?? ''));
        $host = strtolower((string) ($parts['host'] ?? ''));
        $host = rtrim($host, '.');

        if (!in_array($scheme, ['http', 'https'], true) || $host === '') {
            return [];
        }

        $host = $this->safeHost($host);

        if ($host === null) {
            return [];
        }

        $port = isset($parts['port'])
            ? ':' . $parts['port']
            : '';
        $normalized = $scheme . '://' . $host . $port;

        return [
            'target_host' => $host,
            'target_hash' => hash('sha256', $normalized),
        ];
    }

    /**
     * Hash a client address when a hash key is configured.
     *
     * @param mixed $value The raw client address.
     *
     * @return string|null The HMAC identifier, or null when not configured.
     */
    private function clientHash(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $value = $this->normalizeString($value);

        if ($value === '') {
            return null;
        }

        $key = $this->hashKey;

        if ($key === null || trim($key) === '') {
            return null;
        }

        return 'hmac-sha256:' . hash_hmac('sha256', $value, $key);
    }

    /**
     * Sanitize a single allowlisted value by key.
     */
    private function sanitizeValue(string $key, mixed $value): mixed
    {
        if ($key === 'request_id') {
            return is_string($value) && preg_match('/^[a-f0-9]{32}$/', $value) === 1
                ? $value
                : null;
        }

        if ($key === 'status') {
            return is_int($value) && $value >= 100 && $value <= 599 ? $value : null;
        }

        if (
            in_array(
                $key,
                [
                    'body_bytes',
                    'max_bytes',
                    'declared_bytes',
                    'limit',
                    'remaining',
                    'retry_after',
                    'max_concurrent',
                    'exception_line',
                ],
                true,
            )
        ) {
            return is_int($value) && $value >= 0 ? $value : null;
        }

        if (in_array($key, ['has_authorization', 'session_present'], true)) {
            return is_bool($value) ? $value : null;
        }

        if ($key === 'error_codes') {
            return $this->sanitizeList($value);
        }

        if ($key === 'method') {
            return $this->safeMethod($value);
        }

        if ($key === 'path') {
            return $this->safePath($value);
        }

        if ($key === 'reason') {
            return $this->safeEnum($value, self::SAFE_REASONS);
        }

        if ($key === 'engine') {
            return $this->safeEnum($value, self::SAFE_ENGINES);
        }

        if ($key === 'tier') {
            return $this->safeEnum($value, self::SAFE_TIERS);
        }

        if ($key === 'content_type') {
            return $this->safeContentType($value);
        }

        if ($key === 'exception_class') {
            return $this->safeExceptionClass($value);
        }

        if ($key === 'exception_file') {
            return $this->safeExceptionFile($value);
        }

        return null;
    }

    /**
     * Reduce a URL host to a safe DNS name or bracketed IP address.
     */
    private function safeHost(string $host): ?string
    {
        if (str_starts_with($host, '[') && str_ends_with($host, ']')) {
            $address = substr($host, 1, -1);

            return preg_match('/^[0-9a-f:.]+$/', $address) === 1 ? $host : null;
        }

        if (strlen($host) > self::MAX_HOST_BYTES) {
            return null;
        }

        return preg_match('/^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/', $host) === 1
            ? $host
            : null;
    }

    /**
     * Return a value only when it is one of the approved identifiers.
     *
     * @param list<string> $allowed The approved identifiers.
     */
    private function safeEnum(mixed $value, array $allowed): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $value = $this->normalizeString($value);

        if ($value === '' || strlen($value) > self::MAX_IDENTIFIER_BYTES) {
            return null;
        }

        return in_array($value, $allowed, true) ? $value : null;
    }

    /**
     * Normalize an HTTP method to an approved value.
     */
    private function safeMethod(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $method = strtoupper($this->normalizeString($value));

        if ($method === '') {
            return null;
        }

        if (strlen($method) > 16) {
            return 'OTHER';
        }

        return in_array($method, self::SAFE_METHODS, true) ? $method : 'OTHER';
    }

    /**
     * Return a known application path or null for unknown paths.
     */
    private function safePath(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $path = $this->normalizeString($value);
        $path = substr($path, 0, strcspn($path, '?#'));

        if ($path === '' || strlen($path) > self::MAX_PATH_BYTES) {
            return null;
        }

        return in_array($path, self::SAFE_PATHS, true) ? $path : null;
    }

    /**
     * Reduce a content type to an approved media type without parameters.
     */
    private function safeContentType(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $value = $this->normalizeString($value);
        $mediaType = strtolower(trim(explode(';', $value, 2)[0]));

        if ($mediaType === '' || strlen($mediaType) > self::MAX_MEDIA_TYPE_BYTES) {
            return null;
        }

        return in_array($mediaType, self::SAFE_MEDIA_TYPES, true) ? $mediaType : 'other';
    }

    /**
     * Return a safe exception class name without anonymous-class metadata.
     */
    private function safeExceptionClass(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $class = $this->normalizeString($value);

        if ($class === '' || strlen($class) > self::MAX_CLASS_BYTES) {
            return null;
        }

        return preg_match('/^[A-Za-z_][A-Za-z0-9_]*(?:\\\\[A-Za-z_][A-Za-z0-9_]*)*$/', $class) === 1
            ? $class
            : null;
    }

    /**
     * Reduce an exception file to a safe basename without directory paths.
     */
    private function safeExceptionFile(mixed $value): ?string
    {
        if (!is_string($value)) {
            return null;
        }

        $path = $this->normalizeString($value);
        $path = str_replace('\\', '/', $path);
        $file = basename($path);

        if (
            $file === ''
            || $file === '.'
            || $file === '..'
            || strlen($file) > self::MAX_FILE_BYTES
        ) {
            return null;
        }

        return preg_match('/^[A-Za-z0-9._-]+$/', $file) === 1 ? $file : null;
    }

    /**
     * Sanitize a list of safe short identifiers.
     *
     * @param mixed $value The candidate list.
     *
     * @return list<string>|null The sanitized list, or null when invalid.
     */
    private function sanitizeList(mixed $value): ?array
    {
        if (!is_array($value)) {
            return null;
        }

        $items = [];

        foreach ($value as $item) {
            $safe = $this->safeEnum($item, self::SAFE_ERROR_CODES);

            if ($safe === null) {
                continue;
            }

            $items[] = $safe;

            if (count($items) >= self::MAX_LIST_ITEMS) {
                break;
            }
        }

        return $items === [] ? null : $items;
    }

    /**
     * Strip control characters and normalize invalid UTF-8.
     */
    private function normalizeString(string $value): string
    {
        $value = $this->normalizeUtf8($value);
        $value = preg_replace('/[\x00-\x1F\x7F]/', '', $value) ?? '';

        return preg_replace('/[\x{0080}-\x{009F}\x{2028}\x{2029}]/u', '', $value) ?? '';
    }

    /**
     * Replace invalid UTF-8 sequences without requiring mbstring.
     */
    private function normalizeUtf8(string $value): string
    {
        if (preg_match('//u', $value) === 1) {
            return $value;
        }

        $encoded = json_encode($value, JSON_INVALID_UTF8_SUBSTITUTE);

        if (!is_string($encoded)) {
            return '';
        }

        $decoded = json_decode($encoded, true);

        return is_string($decoded) ? $decoded : '';
    }
}
