<?php

declare(strict_types=1);

namespace Tests\Integration\Web;

use App\Core\Application;
use App\Core\Container;
use App\Core\Dispatcher;
use App\Core\ExceptionHandler;
use App\Core\Kernel;
use App\Core\Request;
use App\Core\Router;
use App\Core\View;
use App\Controllers\AboutController;
use App\Controllers\HomeController;
use App\Controllers\LoadingController;
use App\Controllers\SeoController;
use App\Security\CsrfGuard;
use PHPUnit\Framework\Attributes\BackupGlobals;
use PHPUnit\Framework\TestCase;
use RuntimeException;
use SimpleXMLElement;
use Tests\Support\CsrfTestSupport;

/**
 * Verifies the SEO artifacts served by the router.
 *
 * robots.txt and sitemap.xml are generated by SeoController at request
 * time so their content stays in sync with the canonical production origin.
 * Both artifacts must only expose indexable public pages and must never
 * leak local development domains or non-indexable application URLs.
 */
#[BackupGlobals(true)]
final class SeoArtifactsTest extends TestCase
{
    private const PRODUCTION_ORIGIN = 'https://themedetectortool.com';

    private const FORBIDDEN = [
        'themedetector.test',
        'localhost',
        '127.0.0.1',
        'github.com',
        '/detect',
        '/loading',
        '/api',
        '/blog',
        '/docs',
    ];

    public function test_robots_txt_returns_200_with_plain_text_content_type(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/robots.txt'));

        $this->assertSame(200, $response->status());
        $this->assertSame('text/plain; charset=UTF-8', $response->headers()['Content-Type']);
    }

    public function test_robots_txt_allows_crawling_and_declares_production_sitemap(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/robots.txt'));

        $this->assertStringContainsString('User-agent: *', $response->content());
        $this->assertStringContainsString('Allow: /', $response->content());
        $this->assertStringContainsString(
            'Sitemap: ' . self::PRODUCTION_ORIGIN . '/sitemap.xml',
            $response->content(),
        );
    }

    public function test_robots_txt_never_references_local_domains_or_application_urls(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/robots.txt'));

        foreach (self::FORBIDDEN as $needle) {
            $this->assertStringNotContainsString($needle, $response->content());
        }
    }

    public function test_sitemap_returns_200_with_valid_xml(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/sitemap.xml'));

        $this->assertSame(200, $response->status());
        $this->assertSame('application/xml; charset=UTF-8', $response->headers()['Content-Type']);
        $this->assertStringStartsWith('<?xml', $response->content());
        $this->assertInstanceOf(SimpleXMLElement::class, $this->sitemapXml($response->content()));
    }

    public function test_sitemap_lists_homepage_and_about_with_production_urls(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/sitemap.xml'));

        $locations = [];
        foreach ($this->sitemapXml($response->content())->url as $url) {
            $locations[] = (string) $url->loc;
        }

        $this->assertSame(
            [
                self::PRODUCTION_ORIGIN . '/',
                self::PRODUCTION_ORIGIN . '/about',
            ],
            $locations,
        );
    }

    public function test_sitemap_never_references_local_domains_or_application_urls(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/sitemap.xml'));

        foreach (self::FORBIDDEN as $needle) {
            $this->assertStringNotContainsString($needle, $response->content());
        }
    }

    public function test_unknown_seo_routes_return_404(): void
    {
        $response = $this->kernel()->handle($this->request('GET', '/robots.txt/extra'));

        $this->assertSame(404, $response->status());
    }

    private function request(string $method, string $uri): Request
    {
        $request = new Request($method, $uri, [], []);

        $container = $GLOBALS['app'] ?? null;

        if ($container instanceof Container) {
            $container->set(Request::class, $request);
        }

        return $request;
    }

    private function kernel(): Kernel
    {
        $application = new Application();
        $container = $application->container();
        CsrfTestSupport::register($container);

        $container->set(
            View::class,
            static fn (): View => new View(dirname(__DIR__, 3) . '/resources/views'),
        );

        $container->set(
            HomeController::class,
            static fn (): HomeController => new HomeController(),
        );

        $container->set(
            AboutController::class,
            static fn (): AboutController => new AboutController(),
        );

        $container->set(
            LoadingController::class,
            static fn (Container $container): LoadingController => new LoadingController(
                $container->get(CsrfGuard::class),
            ),
        );

        $container->set(
            SeoController::class,
            static fn (): SeoController => new SeoController(),
        );

        $router = new Router();
        $dispatcher = new Dispatcher(container: $container);
        $exceptionHandler = new ExceptionHandler();

        $kernel = new Kernel(
            router: $router,
            dispatcher: $dispatcher,
            exceptionHandler: $exceptionHandler,
        );

        require dirname(__DIR__, 3) . '/routes/web.php';

        $GLOBALS['app'] = $container;

        return $kernel;
    }

    private function sitemapXml(string $content): SimpleXMLElement
    {
        $xml = simplexml_load_string($content);

        if ($xml === false) {
            throw new RuntimeException('Sitemap content is not valid XML.');
        }

        return $xml;
    }
}
